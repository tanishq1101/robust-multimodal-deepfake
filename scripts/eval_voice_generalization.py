"""Out-of-domain check of the voice model: real vs. synthetic speech outside ASVspoof 2019.

Test set: every audio sample of the VITS paper's demo page (github.com/jaywalnut310/vits-demo):
10 genuine recordings (5 LJ Speech, 5 VCTK) and 85 synthetic clips of the same sentences from
Tacotron 2, Glow-TTS, VITS and ablations, plus voice-converted speech. None of it is ASVspoof data.

The voice model is scored the way the app scores audio (mean over 4 s windows) and the way the test
set was scored in training (centre 4 s window). Writes reports/voice_generalization.md and .csv.

Usage:  python scripts/eval_voice_generalization.py [--checkpoint models/audio_asvspoof_3a53cf51/best.pt]
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

import pandas as pd
import requests

from deepfake.analyzer import Analyzer
from deepfake.evaluation.metrics import compute_metrics
from deepfake.inference import DeepfakeDetector

ROOT = Path(__file__).resolve().parents[1]
BASE = "https://raw.githubusercontent.com/jaywalnut310/vits-demo/master/"
CACHE = Path.home() / ".cache" / "deepfake" / "vits_demo"
SYSTEMS = {"gt": "genuine recording", "th": "Tacotron 2 + HiFi-GAN", "thf": "Tacotron 2 + HiFi-GAN (fine-tuned)",
           "gh": "Glow-TTS + HiFi-GAN", "ghf": "Glow-TTS + HiFi-GAN (fine-tuned)", "dp": "VITS (DDP)",
           "vits": "VITS", "melpost": "VITS ablation: mel posterior", "noflow": "VITS ablation: no flow"}
GROUPS = {"ss": "LJ Speech (single speaker)", "ms": "VCTK (multi-speaker)", "sv": "speech variation",
          "as": "ablation study"}


def fetch_all() -> list[Path]:
    page = requests.get(BASE + "index.html", timeout=60).text
    names = sorted(set(re.findall(r"wavs/((?:ss|ms|sv|as)_0[1-5]_[a-z]+\.wav)", page)))
    CACHE.mkdir(parents=True, exist_ok=True)
    for n in names:
        if not (CACHE / n).is_file():
            r = requests.get(BASE + "wavs/" + n, timeout=60)
            r.raise_for_status()
            (CACHE / n).write_bytes(r.content)
    return [CACHE / n for n in names]


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--checkpoint", default=str(ROOT / "models" / "audio_asvspoof_3a53cf51" / "best.pt"))
    p.add_argument("--out", default=str(ROOT / "reports"))
    args = p.parse_args(argv)

    det = DeepfakeDetector(args.checkpoint)
    analyzer = Analyzer(det, None)
    rows = []
    for f in fetch_all():
        group, _, system = f.stem.split("_")
        rows.append({"file": f.name, "group": GROUPS[group], "system": SYSTEMS.get(system, system),
                     "label": int(system != "gt"),
                     "p_windows": analyzer.analyse(f, with_explanation=False)["p_fake"],
                     "p_centre": det.analyse(f, with_explanation=False)["p_fake"]})
    df = pd.DataFrame(rows)
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    df.round(5).to_csv(out / "voice_generalization.csv", index=False)

    summary = []
    for col, how in (("p_windows", "mean over 4 s windows (as in the app)"), ("p_centre", "centre 4 s window (as in training)")):
        m = compute_metrics(df.label, df[col])
        (tn, fp), (fn, tp) = m["confusion_matrix"]
        summary.append({"Scoring": how, "AUC": f'{m["auc"]:.3f}', "EER": f'{100 * m["eer"]:.1f}%',
                        "Real called real": f"{tn} / {tn + fp}", "Fake called fake": f"{tp} / {tp + fn}"})
    per_system = (df.groupby("system").agg(clips=("file", "size"), mean_p_fake=("p_windows", "mean"))
                  .round(3).reset_index().sort_values("mean_p_fake"))
    real = df[df.label == 0][["file", "group", "p_windows", "p_centre"]].round(4)
    md = ["# Voice model outside its training domain", "",
          f"Checkpoint: `{Path(args.checkpoint).parent.name}` (trained on ASVspoof 2019 LA; in-domain test "
          "AUC 0.977, EER 6.2%).", "",
          f"Test set: {len(df)} clips from the VITS paper's demo page, {int((df.label == 0).sum())} genuine "
          f"recordings and {int(df.label.sum())} synthetic. Generated by `scripts/eval_voice_generalization.py`.", "",
          "## Result", "", pd.DataFrame(summary).to_markdown(index=False), "",
          "The model rates almost every clip as fake, genuine recordings included, so its ranking is close to "
          "chance on this data. ASVspoof 2019 LA's genuine speech comes from VCTK speakers, yet the genuine VCTK "
          "clips here score near 1.0: the model keys on recording and editing traits of the ASVspoof files "
          "(for example the silence around each utterance, see Müller et al., 2021) more than on the voice "
          "itself.", "",
          "## Genuine recordings", "", real.to_markdown(index=False), "",
          "## Mean P(fake) per system", "", per_system.to_markdown(index=False), "",
          "## What this means", "",
          "- In the app, a FAKE that rests on the voice model alone comes with a caution note, and the video "
          "verdict can be switched to *face only*.",
          "- A voice model for real-world use needs more varied genuine speech in training (other corpora, "
          "microphones and rooms), silence trimming so the model cannot use the silence shortcut, codec "
          "augmentation (`--robust-augment`), and an out-of-domain test set such as In-the-Wild "
          "(Müller et al., 2022).", ""]
    (out / "voice_generalization.md").write_text("\n".join(md))
    print("\n".join(md[:12]))
    print(f"\nSaved {out / 'voice_generalization.md'}")


if __name__ == "__main__":
    main()
