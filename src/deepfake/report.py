"""Phase 8: collect every result into one Markdown report + a figures folder.

Scans <data_root> for:
  processed/<dataset>/index.csv                dataset sizes per split / label
  checkpoints/<run>/config.json, history.csv,  every training run and its test metrics,
    test/metrics.json, test/per_category.csv     curves and ROC plots
  outputs/compare_*/comparison.md|png          Phase 4 comparison tables
  outputs/robustness_*/robustness.md|png       Phase 5 stress tests
  outputs/gallery_*/gallery.csv + PNGs         Phase 6 Grad-CAM examples
and writes <out>/results.md + <out>/figures/. Sections with no data say "Not run yet": the
report never contains a number that was not produced by an actual run.
A hand-written <out>/observations.md, if present, is included at the end.

Usage:
  python -m deepfake.report                    # -> <data_root>/report/   (Drive on Colab)
  python -m deepfake.report --out reports      # -> the repo's reports/ folder
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import shutil
from pathlib import Path

import pandas as pd

from deepfake.config import get_path, load_config

NOT_RUN = "_Not run yet._"


def _md_table(df: pd.DataFrame, floatfmt: str = ".4f") -> str:
    return df.to_markdown(index=False, floatfmt=floatfmt) if len(df) else NOT_RUN


def dataset_section(processed: Path) -> str:
    rows = []
    for index in sorted(processed.glob("*/index.csv")):
        df = pd.read_csv(index, keep_default_na=False)
        df = df[df["error"] == ""] if "error" in df else df
        for split in ("train", "val", "test"):
            s = df[df.split == split]
            rows.append({"dataset": index.parent.name, "split": split, "clips": len(s),
                         "fake": int((s.label == 1).sum()), "real": int((s.label == 0).sum())})
    return _md_table(pd.DataFrame(rows))


def collect_runs(checkpoints: Path) -> pd.DataFrame:
    rows = []
    for cfg_file in sorted(checkpoints.glob("*/config.json")):
        run = cfg_file.parent
        rc = json.loads(cfg_file.read_text())
        m_file = run / "test" / "metrics.json"
        m = json.loads(m_file.read_text()) if m_file.exists() else {}
        hist = pd.read_csv(run / "history.csv") if (run / "history.csv").exists() else pd.DataFrame()
        rows.append({
            "run": run.name, "task": rc.get("task"), "dataset": Path(rc.get("index", "")).parent.name,
            "fusion": rc.get("fusion", "") if rc.get("task") == "fusion" else "",
            "robust": bool(rc.get("robust_augment")), "pretrained_from": Path(rc["init_from"]).parent.name
            if rc.get("init_from") else "", "epochs": len(hist), "best_epoch": m.get("best_epoch", ""),
            "test_n": m.get("n", ""), "test_auc": m.get("auc"), "test_eer": m.get("eer"),
            "test_acc": m.get("accuracy"), "test_f1": m.get("f1"),
        })
    return pd.DataFrame(rows)


def _copy(src: Path, figures: Path, name: str) -> str | None:
    if not src.exists():
        return None
    figures.mkdir(parents=True, exist_ok=True)
    shutil.copy2(src, figures / name)
    return f"figures/{name}"


def build_report(cfg: dict, out: Path) -> Path:
    out.mkdir(parents=True, exist_ok=True)
    figures = out / "figures"
    ckpts, outputs = get_path(cfg, "checkpoints"), get_path(cfg, "outputs")
    v, a = cfg["video"], cfg["audio"]
    md = ["# Results", "",
          f"_Generated by `python -m deepfake.report` on {dt.date.today().isoformat()} from the "
          f"`{Path(cfg['data_root']).name}` data folder. "
          "Every number below comes from a saved run; missing sections have not been run yet._", "",
          "## Setup", "",
          "| Item | Value |", "|---|---|",
          f"| Frames per video | {v['num_frames']} uniform · {v['face_size']}² YuNet face crops (margin {v['face_margin']}) |",
          f"| Audio | {a['sample_rate'] // 1000} kHz · {a['n_mels']}-bin log-mel · {a['window_seconds']:.0f} s window |",
          f"| Splits | identity-wise, val {cfg['splits']['val_ratio']:.0%} / test {cfg['splits']['test_ratio']:.0%} "
          "(official splits kept for ASVspoof and the Celeb-DF test list) |",
          f"| Seed | {cfg['seed']} |", "",
          "## Datasets", "", dataset_section(get_path(cfg, "processed")), ""]

    runs = collect_runs(ckpts)
    md += ["## Training runs (test split of the training dataset)", "", _md_table(runs), ""]
    for task, title in [("visual", "Phase 2: Visual branch"), ("audio", "Phase 3: Audio branch"),
                        ("fusion", "Phase 4: Fusion models")]:
        md += [f"## {title}", ""]
        sub = runs[runs.task == task] if len(runs) else runs
        if not len(sub):
            md += [NOT_RUN, ""]
            continue
        for r in sub.itertuples():
            run = ckpts / r.run
            md += [f"### `{r.run}`", ""]
            if r.test_auc is not None and r.test_auc == r.test_auc:
                md += [f"Test AUC **{r.test_auc:.4f}** · EER {r.test_eer:.4f} · accuracy {r.test_acc:.4f} · "
                       f"F1 {r.test_f1:.4f} (n = {r.test_n}, best epoch {r.best_epoch})", ""]
            cat = run / "test" / "per_category.csv"
            if cat.exists():
                md += ["Per category:", "", _md_table(pd.read_csv(cat, keep_default_na=False)), ""]
            calib = run / "calibration.csv"
            if calib.exists():
                best = pd.read_csv(calib).iloc[0]
                md += [f"Late-fusion rule chosen on validation: **{best.rule}** (visual weight {best.weight}, "
                       f"val AUC {best.val_auc:.4f})", ""]
            figs = [_copy(run / "curves.png", figures, f"{r.run}_curves.png"),
                    _copy(run / "test" / "roc.png", figures, f"{r.run}_roc.png")]
            md += [f"![]({f})" for f in figs if f] + [""]

    md += ["## Phase 4: Model comparison (overall label, same test set)", ""]
    comps = sorted(outputs.glob("compare_*/comparison.md"))
    for c in comps:
        md += [f"### `{c.parent.name}`", "", c.read_text().replace("## ", "#### "), ""]
        f = _copy(c.parent / "comparison.png", figures, f"{c.parent.name}.png")
        md += [f"![]({f})", ""] if f else []
    md += [] if comps else [NOT_RUN, ""]

    md += ["## Phase 5: Robustness", ""]
    robs = sorted(outputs.glob("robustness_*/robustness.md"))
    for r in robs:
        md += [f"### `{r.parent.name}`", "", r.read_text().replace("## ", "#### "), ""]
        f = _copy(r.parent / "robustness.png", figures, f"{r.parent.name}.png")
        md += [f"![]({f})", ""] if f else []
    md += [] if robs else [NOT_RUN, ""]

    md += ["## Phase 6: Explainability (Grad-CAM)", ""]
    gals = sorted(outputs.glob("gallery_*/gallery.csv"))
    for g in gals:
        table = pd.read_csv(g, keep_default_na=False)
        md += [f"### `{g.parent.name}`", "", _md_table(table.drop(columns=["file"]), ".3f"), ""]
        for row in table.groupby(["category", "outcome"]).head(1).itertuples():
            f = _copy(g.parent / row.file, figures, f"{g.parent.name}__{row.file}")
            if f:
                md += [f"**{row.category} · {row.outcome}** (P(fake) {row.p_fake:.3f})", "", f"![]({f})", ""]
    md += [] if gals else [NOT_RUN, ""]

    obs = out / "observations.md"
    md += ["## Observations", "", obs.read_text() if obs.exists() else
           "_Write your observations in `observations.md` next to this file; they are included here._", ""]
    (out / "results.md").write_text("\n".join(md))
    runs.to_csv(out / "runs.csv", index=False)
    print(f"Report: {out / 'results.md'} ({len(runs)} runs, {len(comps)} comparisons, {len(robs)} robustness, "
          f"{len(gals)} galleries)")
    return out / "results.md"


def main(argv=None) -> Path:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--out", help="output folder (default <data_root>/report)")
    args = p.parse_args(argv)
    cfg = load_config()
    return build_report(cfg, Path(args.out) if args.out else Path(cfg["data_root"]) / "report")


if __name__ == "__main__":
    main()
